function clone(x){return JSON.parse(JSON.stringify(x))}
function esc(v){return String(v??'').replace(/[&<>"']/g,m=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[m]))}
function load(){
 try{
  const raw=localStorage.getItem(KEY),d=raw?JSON.parse(raw):null;
  if(d&&Array.isArray(d.suppliers)&&Array.isArray(d.locations)&&Array.isArray(d.warehouses)){
   /* One-time cleanup of the old autogenerated Dobavljač 1..262 catalog.
      User-created/custom suppliers are preserved. */
   let dirty=false;
   // Quarantine obsolete autogenerated SUP001..SUP262 placeholders on every read,
   // including clients that previously set the one-time migration flag.
   const clean=d.suppliers.filter(x=>{
     const id=String(x?.id||''),name=String(x?.name||'');
     const m=id.match(/^SUP(\d{3})$/);
     if(!m)return true;
     const n=Number(m[1]);
     return !(n>=1&&n<=262&&name===`Dobavljač ${n}`);
   });
   if(clean.length!==d.suppliers.length){d.suppliers=clean;dirty=true}
   if(!d.__emptySupplierSeedMigrationV583){d.__emptySupplierSeedMigrationV583=true;dirty=true}
   /* A missing migration flag is not evidence that a warehouse is obsolete.
      Never delete configured Master warehouses on read. A previous migration
      could silently wipe valid W001 etc. and break account/booking flows. */
   if(!d.__emptyWarehouseMigrationV583){
     d.__emptyWarehouseMigrationV583=true;
     dirty=true;
   }
   // Do not write localStorage every time a view reads Master Data.
   if(dirty)try{localStorage.setItem(KEY,JSON.stringify(d))}catch(_){}
   return d;
  }
 }catch(_){}
 const d=clone(seed);d.__emptyWarehouseMigrationV583=true;return d;
}
